// «Иван, Мария и Пётр».
function list(names) {
  return names.length > 1 ? `${names.slice(0, -1).join(', ')} и ${names.at(-1)}` : names[0] || '';
}
// Имя с отчеством, как к человеку обращаются: «Мария Ивановна».
const called = (p) => (p ? [p.given, p.patronymic].filter(Boolean).join(' ') || (p.surname ? fullName(p) : '') : '');

// Имена родных того, у кого берут интервью: мама, папа, муж или жена (последний брак), дети, бабушки и дедушки.
export function namesFor(idx, id) {
  const person = (x) => idx?.persons.get(x);
  const empty = { mother: '', father: '', spouse: '', spouseWord: '', children: [], grand: [] };
  if (!person(id)) return empty;
  const parents = parentsOf(idx, id).map(person).filter(Boolean);
  const mother = parents.find((p) => p.sex === 'F');
  const father = parents.find((p) => p.sex === 'M');
  const spouse = spousesOf(idx, id).map((s) => person(s.spouseId)).filter(Boolean).at(-1);
  const grand = [mother, father].filter(Boolean).flatMap((p) => parentsOf(idx, p.id).map(person).filter(Boolean));
  return {
    mother: called(mother),
    father: called(father),
    spouse: called(spouse),
    spouseWord: spouse?.sex === 'F' ? 'Ваша жена' : spouse?.sex === 'M' ? 'Ваш муж' : 'Ваш муж или жена',
    children: childrenOf(idx, id).map((c) => person(c)?.given).filter(Boolean),
    grand: grand.map(called).filter(Boolean).slice(0, 4),
  };
}

// Вопросы выбранных тем по порядку: [{ key, topic, text }]. Ключ постоянный: «parents.1» — второй вопрос темы.
export function buildQuestions(topics, names) {
  const n = { ...namesFor(null, null), ...names };
  return TOPICS.filter((t) => topics.includes(t.key))
    .flatMap((t) => t.questions.map((x, i) => ({ key: `${t.key}.${i}`, topic: t.key, text: typeof x === 'function' ? x(n) : x })));
}

// «Интервью 24 октября», в прошлые годы — с годом.
export function ivTitle(at, now = new Date()) {
  const d = new Date(at);
  const opts = { day: 'numeric', month: 'long', timeZone: 'Europe/Moscow' };
  if (d.getFullYear() !== now.getFullYear()) opts.year = 'numeric';
  return `Интервью ${d.toLocaleDateString('ru-RU', opts).replace(/\s*г\.$/, '')}`;
}

